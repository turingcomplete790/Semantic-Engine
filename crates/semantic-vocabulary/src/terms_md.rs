use crate::{TermKind, Vocabulary, NS};

fn short(iri: &str) -> String {
    iri.strip_prefix(NS)
        .map(|s| format!("`{s}`"))
        .unwrap_or_else(|| iri.to_string())
}

fn cell(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

pub fn generate(v: &Vocabulary) -> String {
    let mut out = String::new();
    out.push_str("# Terms\n\n");
    out.push_str("Generated by `vocab-check --write-terms`; do not edit.\n\n");
    out.push_str(&format!(
        "Vocabulary version {}. Namespace `{}`.\n\n",
        v.version().unwrap_or_else(|| "unknown".into()),
        NS
    ));
    let terms: Vec<_> = v.terms().collect();
    for (title, kind) in [
        ("Classes", TermKind::Class),
        ("Properties", TermKind::Property),
    ] {
        out.push_str(&format!("## {title}\n\n"));
        if kind == TermKind::Class {
            out.push_str("| Term | Subclass of | Scope | Status | Definition | Source |\n|---|---|---|---|---|---|\n");
        } else {
            out.push_str("| Term | Domain | Range | Scope | Status | Definition | Source |\n|---|---|---|---|---|---|---|\n");
        }
        let mut list: Vec<_> = terms.iter().filter(|t| t.kind == kind).collect();
        list.sort_by_key(|t| t.local().to_lowercase());
        for t in list {
            let scope = t
                .values("scope")
                .first()
                .map(|s| short(s))
                .unwrap_or_else(|| "–".into());
            let status = t
                .values("status")
                .first()
                .map(|s| short(s))
                .unwrap_or_default();
            let status = status.trim_matches('`').to_string();
            let comment = t
                .values("rdfs:comment")
                .first()
                .cloned()
                .unwrap_or_default();
            let src = t.values("source").join("; ");
            let mut def = comment;
            if let Some(r) = t.values("replacedBy").first() {
                def.push_str(&format!(" Replaced by {}.", short(r)));
            }
            if let Some(n) = t.values("retiredNote").first() {
                def.push_str(&format!(" {n}"));
            }
            if kind == TermKind::Class {
                let sub: Vec<String> = t
                    .values("rdfs:subClassOf")
                    .iter()
                    .map(|s| short(s))
                    .collect();
                out.push_str(&format!(
                    "| `{}` | {} | {} | {} | {} | {} |\n",
                    t.local(),
                    if sub.is_empty() {
                        "–".into()
                    } else {
                        sub.join(", ")
                    },
                    scope,
                    status,
                    cell(&def),
                    cell(&src)
                ));
            } else {
                let d = t
                    .values("rdfs:domain")
                    .first()
                    .map(|s| short(s))
                    .unwrap_or_default();
                let r = t
                    .values("rdfs:range")
                    .first()
                    .map(|s| {
                        s.strip_prefix(crate::XSD)
                            .map(|x| format!("xsd:{x}"))
                            .unwrap_or_else(|| short(s))
                    })
                    .unwrap_or_default();
                out.push_str(&format!(
                    "| `{}` | {} | {} | {} | {} | {} | {} |\n",
                    t.local(),
                    d,
                    r,
                    scope,
                    status,
                    cell(&def),
                    cell(&src)
                ));
            }
        }
        out.push('\n');
    }

    out.push_str("## Stash data mapping\n\n| Stash field | Entity | Allowed values | Produces | Status |\n|---|---|---|---|---|\n");
    let mut maps = v.mapping_rows();
    maps.sort();
    for r in maps {
        out.push_str(&format!(
            "| `{}` | {} | {} | {} | {} |\n",
            r.0,
            r.1,
            cell(&r.2),
            r.3,
            r.4
        ));
    }
    out.push_str("\n## Not mapped (retired)\n\n| Stash field | Entity | Why not read | Replaced by |\n|---|---|---|---|\n");
    let mut ret = v.retired_rows();
    ret.sort();
    for r in ret {
        out.push_str(&format!(
            "| `{}` | {} | {} | {} |\n",
            r.0,
            r.1,
            cell(&r.2),
            r.3
        ));
    }
    out
}
