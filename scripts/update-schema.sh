#!/usr/bin/env sh
# Regenerate the pinned Stash GraphQL schema from a Stash source tree (research R3).
# Usage: scripts/update-schema.sh /path/to/stash-source VERSION
set -eu
src="${1:?path to the Stash source tree}"
ver="${2:?Stash version, for example v0.31.1}"
out="schemas/stash-${ver}.graphql"
dir="$src/graphql/schema"
[ -f "$dir/schema.graphql" ] || { echo "no $dir/schema.graphql" >&2; exit 1; }
{
    echo "# Stash GraphQL schema ${ver}, pinned for the Cynic adapter (constitution v1.1.0)."
    echo "# Generated by scripts/update-schema.sh from graphql/schema/schema.graphql and"
    echo "# graphql/schema/types/*.graphql of the Stash ${ver} source on $(date +%Y-%m-%d). Do not edit."
    echo
    cat "$dir/schema.graphql"
    # Pathname expansion is sorted; LC_ALL=C makes the order byte-wise and reproducible.
    LC_ALL=C
    export LC_ALL
    for f in "$dir"/types/*.graphql; do
        echo
        echo "# ---- $(basename "$f")"
        cat "$f"
    done
} > "$out"
echo "wrote $out"
